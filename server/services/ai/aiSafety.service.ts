import { AiSecurityPolicyService } from './aiSecurityPolicy.service.js';
import type {
  RedactionResult,
  InputValidationResult,
  OutputValidationResult,
} from './aiSecurityPolicy.service.js';

export type { RedactionResult, InputValidationResult, OutputValidationResult };

export class AiSafetyService {
  /**
   * Redacts known patterns and configured application secrets from text or objects.
   */
  static redactSecrets<T = unknown>(input: T): RedactionResult<T> {
    return AiSecurityPolicyService.redactSecrets(input);
  }

  /**
   * Validates user input prompts against length limits, emptiness, and injection attacks.
   */
  static validateInput(prompt: unknown): {
    valid: boolean;
    sanitizedPrompt: string;
    errorCode?:
      | 'PROMPT_REQUIRED'
      | 'PROMPT_TOO_LONG'
      | 'PROMPT_INJECTION_DETECTED'
      | 'UNSAFE_INSTRUCTION_DETECTED'
      | 'SECRET_EXTRACTION_DETECTED'
      | 'ROLE_SPOOFING_DETECTED'
      | 'CROSS_TENANT_VIOLATION'
      | 'CONFIRMATION_BYPASS_ATTEMPT';
    message?: string;
  } {
    const result = AiSecurityPolicyService.validateInput(prompt);
    return {
      valid: result.valid,
      sanitizedPrompt: result.sanitizedPrompt,
      errorCode: result.errorCode,
      message: result.message,
    };
  }

  /**
   * Checks whether the provided text contains ungrounded or prohibited guaranteed outcome claims.
   */
  static checkForGuaranteedClaims(text: string): boolean {
    const result = AiSecurityPolicyService.validateOutput(text);
    return result.hasGuaranteedClaims;
  }

  /**
   * Sanitizes output generated by models or fallback builders.
   */
  static sanitizeOutput(output: string): { sanitized: string; redactedCount: number } {
    return AiSecurityPolicyService.redactSecrets(output);
  }

  /**
   * Sanitizes untrusted community/external text before prompt inclusion.
   */
  static sanitizeUntrustedContent(content: string): string {
    return AiSecurityPolicyService.sanitizeUntrustedContent(content);
  }
}
